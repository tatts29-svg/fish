const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const dir = path.resolve(__dirname, '..');
const basePath = process.env.BASE || path.resolve(dir, '../build/GC500_v9.93-final/GC500_Delivery_Control_hosted.html');
const candidatePath = process.env.PAGE;
const base = fs.readFileSync(basePath, 'utf8');
const dataOf = html => JSON.parse(html.match(/const DATA = (.+);\n/)[1]);
const data = dataOf(base);
const source = fs.readFileSync(path.join(dir, 'generators994.js'), 'utf8');
const context = vm.createContext({DATA: data});
vm.runInContext(source, context);
const plain = value => JSON.parse(JSON.stringify(value));
const asset = data.assets.find(a => a.key === 'GN?');
const event = asset.events.find(e => e.task_id === 'T0260');
const loads = event.booking801.loads;
const rows = data.rental_on_hire.rows;
const before = JSON.stringify([data, asset, event, loads]);
const numbers = (a=asset, e=event, l=loads[0], rr=rows) => plain(context.generatorBookingNumbers994(a,e,l,rr));
assert.equal(context.generatorRefLabel994('GN?'), 'Concert');
assert.equal(context.generatorRefLabel994('GN13'), 'GN13');
assert.equal(context.generatorRefLabel994(null), '');
const locationSource={text:'Generator',raw:'GN13 - Generator',source:'schedule',known:true};
context.dest782=()=>({kind:'master',ll:{lat:-27.9883915,lon:153.4300855}});
const located=plain(context.generatorDestination994({key:'GN13'},locationSource));
assert.equal(located.text,'SLS Equipment Compound · Narrowneck');
assert.equal(located.raw,'GN13 - Generator');
assert.equal(located.confidence,'drawing');
assert.equal(context.generatorDestination994({key:'GN?'},locationSource),locationSource);
assert.equal(context.generatorDestination994({key:'GN13',_locationMoved:{to:'New destination'}},locationSource),locationSource);
context.dest782=()=>({kind:'pinned',ll:{lat:-27.9883915,lon:153.4300855}});
assert.equal(context.generatorDestination994({key:'GN13'},locationSource),locationSource);
context.dest782=()=>({kind:'master',ll:{lat:-27.99,lon:153.43}});
assert.equal(context.generatorDestination994({key:'GN13'},locationSource),locationSource);
assert.deepEqual(numbers(), ['1316182']);
assert.deepEqual(numbers(asset,event,loads[1]), ['1316183']);
assert.deepEqual(numbers(asset,event,loads[0],rows.slice().reverse()), ['1316182'], 'not source order');
assert.equal(loads[0].load_time, '11:00');
assert.equal(loads[1].load_time, '11:30');
assert.deepEqual(numbers(asset,event,{...loads[0],dd:'26121298 / 26121310'}), [], 'ambiguous DD rejected');
assert.deepEqual(numbers(asset,event,{...loads[0],dd:'missing'}), []);
assert.deepEqual(numbers(asset,event,{...loads[0],quantity:2}), [], 'no allocation when count differs');
assert.deepEqual(numbers(asset,{...event,date:'2026-10-13'}), [], 'a moved booking needs its own matching source');
assert.deepEqual(numbers(asset,{...event,task_id:'other'}), []);
assert.deepEqual(numbers({...asset,key:'GN13'}), [], 'other generators unaffected');
assert.deepEqual(numbers({...asset,asset_numbers:['1316183']}), [], 'unit outside allocation rejected');
assert.deepEqual(numbers(asset,event,loads[0],rows.filter(r=>String(r.asset_no)!=='1316182')), []);
assert.deepEqual(numbers(asset,event,loads[0],rows.map(r=>({...r,asset_no_is_plant_number:false}))), []);
assert.deepEqual(numbers(asset,event,loads[0],rows.map(r=>({...r,match:{key:'GN13'}}))), []);
assert.deepEqual(numbers(asset,event,{...loads[0],asset_numbers:['explicit']}), ['explicit'], 'supplied booking stays authoritative');
assert.deepEqual(numbers(asset,event,loads[0],rows.concat(rows)), ['1316182'], 'duplicate source rows do not duplicate units');
const conflict = {...rows.find(r=>String(r.asset_no)==='1316183'), delivery_number:'26121298'};
assert.deepEqual(numbers(asset,event,loads[0],rows.concat(conflict)), [], 'two different units for one single-unit docket rejected');
assert.equal(JSON.stringify([data, asset, event, loads]), before, 'no mutation of source, event or booking');
if (candidatePath) {
  const candidate = fs.readFileSync(candidatePath, 'utf8');
  assert.deepEqual(dataOf(candidate), data, 'all embedded source, rates, dates and positions remain identical');
  const start = candidate.indexOf('function bookingGroups801(d){');
  const end = candidate.indexOf('\nfunction bookingLoads801(d)', start);
  assert.ok(start>0 && end>start);
  context.bookingRows801=(a, events)=>(events||a.events).filter(e=>e.booking801&&!e.bookingMoved801).map(e=>({a,e,b:e.booking801}));
  context.bookingSort801=(a,b)=>String(a.time).localeCompare(String(b.time));
  context.dpT=t=>t;
  vm.runInContext(candidate.slice(start,end),context);
  const groups=plain(context.bookingGroups801({deliveries:[{a:asset,events:[event]}]}));
  assert.equal(groups.length,2);
  assert.deepEqual(groups.map(g=>[g.rows[0].a.key,g.rows[0].a.asset_numbers,g.rows[0].a._bookingNumbers801,g.dds,g.time]),[
    ['GN?',['1316182'],['1316182'],['26121298'],'11:00'],
    ['GN?',['1316183'],['1316183'],['26121310'],'11:30']
  ]);
  assert.equal(groups[0].rows[0].a.events[0].quantity_raw,1);
  assert.equal(groups[1].rows[0].a.events[0].quantity_raw,1);
  assert.ok(candidate.includes('data-tl841-ref="\' + esc(asset.key)'));
  assert.ok(candidate.includes('generatorBookingNumbers994(a,e,l).join'));
  assert.equal(JSON.stringify([data, asset, event, loads]),before);
}
console.log('PASS: Concert labels, exact per-DD assets, conflicting/moved/missing source guards, untouched data and record keys.');
