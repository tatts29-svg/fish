'use strict';
const assert=require('assert/strict'),api=require('./selection_save1012.js');let checks=0;
const yes=(condition,label)=>{assert.ok(condition,label);checks++;};
const doc={collection:'rates',id:'one',expected:'{"value":100}'},a={accepted:true,kept:true,expected:[doc]},env={ready:true,connected:true,unkept:false,last:{rates:{one:doc.expected}},queue:{},inflight:{},current:()=>doc.expected};
const state=(at=a,en=env)=>api.status(at,en).state;
yes(state()==='shared','exact acknowledgement');
yes(state({...a,dirty:true})==='dirty','typed draft never claimed saved');
yes(state({...a,error:'Invalid entry'})==='error','rejected edit never acknowledged');
yes(state({...a,kept:false})==='error','persistence failure');
yes(state(a,{...env,unkept:true})==='error','device storage failure');
yes(state({...a,expected:[]})==='idle','empty expected set cannot confirm');
yes(state({...a,accepted:false})==='idle','no native acceptance cannot confirm');
yes(state(a,{...env,current:()=>'{"value":101}'})==='changed','changed record invalidates earlier acknowledgement');
yes(state(a,{...env,last:{}})==='local','no server acknowledgement');
yes(state(a,{...env,queue:{rates:{one:null}}})==='local','queued removal is pending by own key');
yes(state(a,{...env,inflight:{'rates/one':null}})==='local','null inflight is still pending');
yes(state(a,{...env,ready:false})==='local','collection/readiness incomplete');
yes(api.status(a,{...env,ready:false,connected:false}).text.includes('waiting for connection'),'offline is device-only');
const removed={accepted:true,kept:true,expected:[{collection:'rates',id:'one',expected:null}]},remenv={...env,current:()=>null,last:{rates:{}}};
yes(state(removed,remenv)==='shared','acknowledged native deletion');
yes(state(removed,{...remenv,queue:{rates:{one:null}}})==='local','unacknowledged deletion');
yes(state(removed,{...remenv,last:{rates:{one:'{}'}}})==='local','server still has deleted record');
yes(state(removed,{...remenv,current:()=>'{"value":100}'})==='changed','recreated record invalidates deletion confirmation');
const pair={...a,expected:[doc,{collection:'by',id:'one',expected:'{"value":"Andrew"}'}]};
yes(state(pair,{...env,current:(c)=>c==='rates'?doc.expected:'{"value":"Andrew"}'})==='local','partial ACK cannot claim success');
yes(state(pair,{...env,current:(c)=>c==='rates'?doc.expected:'{"value":"Andrew"}',last:{rates:{one:doc.expected},by:{one:'{"value":"Andrew"}'}}})==='shared','all field and audit docs acknowledged');
yes(api.diff({rates:{one:'{"value":100}'}},{rates:{one:'{"value":101}'}}).length===1,'changed source document');
yes(api.diff({rates:{one:'{"value":100}'}},{rates:{}})[0].expected===null,'removal captured');
yes(api.diff({rates:{}},{rates:{one:'{"value":100}'}})[0].expected===doc.expected,'creation captured');
yes(api.diff({rates:{one:'{"x":1,"y":2}'}},{rates:{one:'{"y":2,"x":1}'}}).length===0,'serialization order alone is no change');
yes(api.families.length===11,'all audited persistent selection families');
yes(api.excluded.includes('data-loading1012-editor'),'loading specialist controls excluded');
yes(!api.families.some(f=>f.selector.includes('data-asm816')||f.selector.includes('#sheetSel')),'local assumptions and navigation not falsely called shared saves');
console.log(JSON.stringify({author:'Andrew Fisher',pass:true,checks}));
