def patch(text):
    if hashlib.sha256(text.encode('utf-8')).hexdigest() != BASE_SHA256: raise ValueError('v10.86 requires the live v10.85 page ' + BASE_SHA256)
    i = text.index(P.OPEN) + len(P.OPEN); j = text.index(P.CLOSE, i)
    new = P.tracker_block()
