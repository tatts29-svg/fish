equal(M.bookingEntries(booking,['OPEN','PART']).entries,[booking.entries[0],booking.entries[1],booking.entries[3]],'Only ambiguous text involving a departed ref is omitted');
equal(JSON.stringify(booking),bookingBefore,'Booking source remains intact');
equal(M.bookingEntries(null,['OPEN']),null,'No booking evidence remains absent');
equal(M.bookingEntries({entries:[],noText:1},[]),{entries:[],noText:1},'Native no-text distinction retained');
let calls=[];
globalThis.Departure1211={status:key=>{calls.push(key);return event;}};
