'use strict';
const assert = require('node:assert/strict');
const M = require('../build_departure1248.js');
let checks = 0;
const check = (yes, message) => {assert(yes, message); checks++;};
const equal = (a,b,message) => {assert.deepEqual(a,b,message); checks++;};
const base = Object.freeze({stage:2,label:'In transit',word:'In transit',tone:'amber',c:'amber',arrived:false,blocked:false,why:'Recorded in transit',said:'Recorded in transit'});
const event = Object.freeze({known:true,unknown:false,issues:[],collected:4,remaining:0,complete:true,arrival:true,last:'28/10/2026, 10:00:00 AEST'});
const before = JSON.stringify({base,event});
const gone = M.project(base,event);
equal(gone.label,'Left site','Full native departure has its own words');
equal(gone.stage,5,'Finished display outcome');
equal(gone.departed1248,true,'One final outcome indicator can replace misleading transit stages');
equal(gone.arrived,false,'A departed item is not presented as currently on site');
check(gone.why.includes(event.last),'Native timestamp passes through without reparsing');
equal(JSON.stringify({base,event}),before,'Projection never mutates source');
check(gone!==base,'Affected display is a new object');
check(!Object.hasOwn(gone,'done'),'No Complete tick invented');
for (const dep of [null,{}, {...event,known:false}, {...event,unknown:true}, {...event,issues:['mismatch']}, {...event,collected:0}, {...event,collected:NaN}, {...event,remaining:-1}, {...event,remaining:NaN}, {...event,complete:true,remaining:1}]) {
 equal(M.project(base,dep),base,'Absent, unknown, conflicting or inconsistent evidence leaves native state intact');
}
