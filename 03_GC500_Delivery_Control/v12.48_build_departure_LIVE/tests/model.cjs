equal(M.project(blocked,event),blocked,'Moved/cancelled native status is preserved');
const partial={...event,complete:false,remaining:6};
const p=M.project(base,partial);
equal(p.label,'On site · 4 of 10 left','Partial departure uses native unit counts');
equal(p.stage,base.stage,'Partial keeps existing setup-stage evidence');
equal(p.arrived,true,'On-site wording requires native arrival proof');
check(!p.departed1248,'Partial is not marked fully left');
check(p.why.includes('6 still to leave'),'Remaining quantity clear');
const uncertain=M.project(base,{...partial,arrival:false});
equal(uncertain.label,'Partial departure · 4 of 10 left','No on-site assertion without arrival proof');
equal(uncertain.arrived,false,'Unknown arrival preserved');
const rows=[{a:{key:'LEFT'}},{a:{key:'PART'}},{a:{key:'OPEN'}},{a:{key:'REVIEW'}}];
const readings={LEFT:event,PART:partial,OPEN:null,REVIEW:{...event,issues:['review']}};
equal(M.activeRows(rows,key=>readings[key]).map(r=>r.a.key),['PART','OPEN','REVIEW'],'Mixed load removes only proved full departure from booking lookup');
equal(M.activeRows([rows[0]],key=>readings[key]),[],'Fully departed load has no obsolete booking band');
equal(M.activeRows([],()=>{throw Error('not called')}),[],'Empty load safe');
const booking={entries:[{ref:'OPEN'},{ref:'OPEN',shared:true},{of:['LEFT','OPEN']},{of:['OPEN','PART']}],noText:0};
